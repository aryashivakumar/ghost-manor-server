function parseGrid() {
  const walls = [];
  const openCells = [];

  for (let z = 0; z < GRID.length; z++) {
    const row = GRID[z];
    for (let x = 0; x < row.length; x++) {
      if (row[x] === '1') {
        walls.push([x, z]);
      } else {
        openCells.push([x, z]);
      }
    }
  }

  return { walls, openCells };
}

